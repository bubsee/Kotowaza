#random list to determine type of grass
randomlist = [[random.randint(0, 3) for _ in range(50)] for _ in range(28)]



def display_floor(screen):
    x = 0
    y = 0
    for row in grid:
        for item in row:
            if item == 0:
                if randomlist[int(y/TILE_WIDTH)][int(x/TILE_WIDTH)] == 0:
                    screen.blit(objects.grass2_tile,(x,y))
                else:
                    screen.blit(objects.grass1_tile, (x,y))
            elif item == 1:
                screen.blit(objects.path_tile, (x,y))
            elif item == 2:
                screen.blit(objects.lake_tile, (x,y))
            x += TILE_WIDTH
        x = 0
        y += TILE_WIDTH